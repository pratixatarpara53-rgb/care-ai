let currentLang = 'en';

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === 'hi' ? 'hi' : 'en';
  document.body.classList.toggle('lang-hi', lang === 'hi');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const str = STRINGS[lang] && STRINGS[lang][key];
    if (str !== undefined) el.textContent = str;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const str = STRINGS[lang] && STRINGS[lang][key];
    if (str !== undefined) el.placeholder = str;
  });

  const btn = document.getElementById('lang-toggle');
  if (btn) btn.textContent = t('langToggle');

  // Highlight active lang button
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active-lang'));
  const active = document.getElementById('lang-' + lang);
  if (active) active.classList.add('active-lang');
}

function t(key) {
  return (STRINGS[currentLang] && STRINGS[currentLang][key]) || STRINGS['en'][key] || key;
}
